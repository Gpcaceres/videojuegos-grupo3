    private void InitializeGame() {
        if (GlobalClassGame.getGameLevel() == 0) {
            ObjectControlTwoUsers.InitializeData();
            ObjectControlTwoUsers.InitializeControls(ListButtons, panTicTacToe);                
        } else if (GlobalClassGame.getGameLevel() == 1) {
            ObjectControlRandomMoves.InitializeData();
            ObjectControlRandomMoves.InitializeControls(ListButtons, panTicTacToe);            
        }
        else if (GlobalClassGame.getGameLevel() == 2)
        {
            ObjectControlWeakIntelligentMoves.InitializeData();
                ObjectControlWeakIntelligentMoves.InitializeControls(ListButtons, panTicTacToe);
        }        
        else if (GlobalClassGame.getGameLevel() == 3)
        {
            ObjectControlStrongIntelligentMoves.InitializeData();
                ObjectControlStrongIntelligentMoves.InitializeControls(ListButtons, panTicTacToe);
        }    
    }

