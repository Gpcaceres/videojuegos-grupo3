    private void btnTicTacToe1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTicTacToe1ActionPerformed
        // TODO add your handling code here:
        if (GlobalClassGame.getGameLevel()== 0) {
            ObjectControlTwoUsers.MarkButton(btnTicTacToe1);
            ObjectControlTwoUsers.CheckWinner(ListButtons, 
                                                   panTicTacToe);
        } else if (GlobalClassGame.getGameLevel() == 1) {
            ObjectControlRandomMoves.PlayUser(btnTicTacToe1, 
                                                     ListButtons, 
                                                     panTicTacToe, 0);
            ObjectControlRandomMoves.PlayNPC(ListButtons, panTicTacToe);
        }
        else if (GlobalClassGame.getGameLevel() == 2)
        {
            ObjectControlWeakIntelligentMoves.PlayUser(btnTicTacToe1, 
                                                     ListButtons, 
                                                     panTicTacToe, 0);
            ObjectControlWeakIntelligentMoves.PlayNPC(ListButtons, panTicTacToe);              
        }
        else if (GlobalClassGame.getGameLevel() == 3)
        {
            ObjectControlStrongIntelligentMoves.PlayUser(btnTicTacToe1, 
                                                     ListButtons, 
                                                     panTicTacToe, 0);
            ObjectControlStrongIntelligentMoves.PlayNPC(ListButtons, panTicTacToe);                
        }       
    }//GEN-LAST:event_btnTicTacToe1ActionPerformed

